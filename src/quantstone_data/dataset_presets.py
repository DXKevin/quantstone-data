class DatasetPreset(BaseModel):
    key: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    category: str
    contract: DatasetCreate


def field(
    name: str,
    data_type: str,
    description: str,
    *,
    nullable: bool = True,
    unit: str | None = None,
    source_name: str | None = None,
) -> dict[str, str | bool | None]:
    return {
        "name": name,
        "data_type": data_type,
        "nullable": nullable,
        "description": description,
        "unit": unit,
        "source_name": source_name or name,
    }


